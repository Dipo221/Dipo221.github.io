# 硬要用字元畫，就得為「被燈照到的磚」「被燈照到的地板」各定義一組跟原色
# 一模一樣、只有發光值不同的重複色，四種材質乘上幾階衰減就是十幾個重複色，
# 而那十幾個色在調色盤上會長得跟已經有的一模一樣。那不是像素畫，那是把
# 一張漸層硬塞進色表裡。
#
# **但它仍然是像素**：它畫在 1x 的 PNG 上，瀏覽器用 `image-rendering: pixelated`
# 放大，所以螢幕上看到的是一格一格的。這一點跟 `.room-beam` 不一樣——
# 那個是 CSS 漸層，它是螢幕解析度的、真的沒有像素。
#
# 明陽比過 4 階、8 階、連續三版（2026-09-04），選了連續：分階在這個尺寸上
# 會跑出等高線，讀起來像地形圖不像光。
