# 逗貓棒。斜靠在牆邊，羽毛在上面。1 格寬、**2 格高**。
#
# 它存在的理由不是裝飾，是**「玩」那個動作需要一個點得到的東西**（待辦第 5 項）。
# 摸有貓可以點、餵有碗可以點，玩本來沒有，那顆按鈕就沒地方去。
#
# 三個決定都是畫出來看了才改的（第一版是 1 格高、直的、羽毛畫成一個圓塊）：
#
# 1. **2 格高。** 1 格只有 16px，配 24px 的貓像一根火柴。32px 比貓高一點，
#    這才是一根靠在牆上的棒子該有的比例。
# 2. **斜的。** 完全直立的一根棒子沒有靠著任何東西，看起來像插在地板上。
#    斜過去 5px 就讀得出來它是「靠著」的。
# 3. **羽毛要有中肋。** 沒有那條 q 的羽毛只是一個亮色塊，圓的更像香菇。
#    羽毛之所以是羽毛就在那條中肋和兩邊對稱的羽枝。
#
# 顏色沒有用綠或布，因為色盤裡還沒有——那三組等 M3 畫到盆栽和沙發
# 再一起進來。羽毛用 Q/q（碗那組陶色）是刻意的：碗和逗貓棒是這個房間裡
# 僅有的兩個「要被點的東西」，同一組顏色等於在說它們是同一類。


def _wand():
    """2x2 的逗貓棒。回傳四塊 16x16 的磚（左上、右上、左下、右下）。"""
    N = 32
    g = [["." for _ in range(N)] for _ in range(N)]

    def px(x, y, ch):
        if 0 <= x < N and 0 <= y < N and (ch != "o" or g[y][x] == "."):
            g[y][x] = ch

    # 握把。**正 45 度**：像素畫裡只有 45 度的斜線不會變成一串階梯，
    # 上一版隨便挑的斜率就是折的，看起來像棒子被折彎了。
    tip = None
    for i in range(20):
        x, y = 3 + i, 30 - i
        for dx, ch in ((-1, "o"), (0, "A"), (1, "A"), (2, "o")):
            px(x + dx, y, ch)
        px(x, y + 1, "o")                          # 下緣，45 度不補這一格會漏光
        tip = (x, y)
    px(tip[0] + 1, tip[1] - 1, "o")

    # 線。從桿尖垂下來——**這條才是逗貓棒的識別特徵**。
    # 上一版沒有它，一根硬棒子加一片葉子讀起來就是一株植物。
    cordy = list(range(tip[1] + 1, tip[1] + 7))
    for j, y in enumerate(cordy):
        px(tip[0] + 2 + (1 if j > 2 else 0), y, "o")
    fx, fy = tip[0] + 3, cordy[-1] + 1

    # 羽毛，吊在線的下端、尖端朝下。上下各一個尖，中間最寬，中間一條中肋
    top, bot = fy, fy + 11
    for y in range(top, bot + 1):
        t = (y - top) / float(bot - top)
        half = int(round(3 * (1 - abs(2 * t - 1)) ** 0.55))
        if half < 1:
            continue
        for dx in range(-half, half + 1):
            px(fx + dx, y, "q" if dx == 0 else "Q")
        px(fx - half - 1, y, "o")
        px(fx + half + 1, y, "o")
    px(fx, top - 1, "o")
    px(fx, bot + 1, "o")

    # 握把落地那一點投在地板上的影
    for dx in range(-2, 3):
        px(3 + dx, 31, "h" if abs(dx) < 2 else "k")

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in (0, 1) for c in (0, 1)]


