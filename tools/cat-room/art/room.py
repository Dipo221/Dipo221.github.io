# 那個（等同 object-fit: contain）。滿版之後那條規則消失了：**20/11 比任何
# 一般螢幕都扁，填滿高度跟塞得下寬度不可能同時成立**，二選一。選了高度，
# 所以桌機左右也會溢出，也跟著貓捲（script.js 的 follow()，那支不用改，
