# 這幾個放在函式外面，理由跟吊燈的 LAMP_DEPTH 那組一模一樣：
# **發光層要用同一組數字算出「哪一塊是螢幕」**（見下面 SCREEN_RECTS）。
# 留在 _desk() 裡面的話，螢幕的位置就會有兩個答案，而錯開一格是看不出來的
# ——發光層本來就是糊的，只會變成邊框有一條微微在亮。
#
# 桌子往房間裡面佔多深：**16 不是隨便挑的**。14 的時候鍵盤跟兩台螢幕的底座
# 在畫面上疊在同一條線上，糊成一坨黑的。桌面深一點，「螢幕在後、鍵盤在前」
# 就自己分開了——那正是深度該做的事。
DESK_DEPTH = 16
DESK_HEIGHT = 26   # 桌面離地多高。床面 21，這張比床高一點才是桌子
MON_D = 5          # 螢幕擺在桌上往裡面第幾格
MON_STAND = 6      # 螢幕下緣離桌面多高
MON_BEZ = 2        # 螢幕邊框多厚
# 左右兩台的左緣（物件格子裡的局部座標）。**兩台一起往右挪了 4 格**，
# 是為了在桌子左端空出一整欄給桌燈——桌燈點得下去，而點得到的東西不能擺在
# 最外面那一兩欄（桌機左右各藏約 1.2 欄）。右邊那台的右緣因此落在 x=301，
# 只有描邊那一格會被預設視角切到，畫面本身（到 x=299）完整。
MON_X = (10, 38)


def _desk():
    """4x6 的書桌，含雙螢幕、鍵盤、滑鼠。回傳 24 塊 16x16 的磚。"""
    depth, height = DESK_DEPTH, DESK_HEIGHT
    slab = 3         # 桌板多厚
    leg = 5          # 桌腳多寬
    mon_d, stand, bez = MON_D, MON_STAND, MON_BEZ
    mw = SCREEN_W + bez * 2      # 一台螢幕連框多寬 = 24
    mh = SCREEN_H + bez * 2      # 連框多高 = 18
    mons = MON_X

    W, H = DESK_W * 16, DESK_H * 16
    off = DESK_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('desk')

    def rect(a, b, c, d, ch):
        for y in range(c, d + 1):
            for x in range(min(a, b), max(a, b) + 1):
                px(x, y, ch)

    def blit(rows, ox, oy):
        for yy, line in enumerate(rows):
            for xx, ch in enumerate(line):
                px(ox + xx, oy + yy, ch)

    def Y(h, d=None):
        return WALL_FOOT + (depth if d is None else d) - h

    x0, x1 = 2, 61                       # 桌板的左右
    tback, tfront = Y(height, 0), Y(height)     # 86, 100
    under = tfront + slab                        # 103，桌板的下緣
    foot = Y(0)                                  # 126

    # 桌板底下那一道影。**只有一道，不是整片填暗**——第一版把 under 到 foot
    # 之間整塊鋪成 h，那是 23 列高的一片黑：桌子當場變成一個沒有門的櫃子。
    # 桌子是有腳的東西，腳跟腳中間本來就看得到踢腳板跟地板，
    # **看得穿才是桌子**
    rect(x0 + 2, x1 - 2, under + 1, under + 3, "h")

    # 兩隻腳。**只畫前面那兩隻**：後面兩隻被桌板擋住了，硬畫出來
    # 等於在說這張桌子是透明的
    for lx in (x0 + 3, x1 - 3 - leg):
        rect(lx, lx + leg, under, foot, "w")
        rect(lx + leg, lx + leg, under, foot, "j")     # 右側背光
        rect(lx, lx, under, foot, "o")
        rect(lx + leg, lx + leg, under, foot, "o")
        rect(lx, lx + leg, foot, foot, "o")
        rect(lx + 1, lx + leg - 1, foot + 1, foot + 1, "h")     # 落地
        rect(lx + 1, lx + leg - 2, foot + 2, foot + 2, "k")

    # 桌板。頂面 -> 分面線 -> 前緣的厚度，跟層架同一套
    rect(x0, x1, tback, tfront, "W")
    rect(x0, x1, tback, tback, "o")
    rect(x0, x1, tback + 1, tback + 1, "A")      # 頂面最靠光的一條
    rect(x0, x1, tfront, tfront, "o")
    rect(x0, x1, tfront + 1, under, "w")
    rect(x0, x1, under, under, "o")
    rect(x0, x0, tback, under, "o")
    rect(x1, x1, tback, under, "o")

    # 螢幕。**兩台之間留 4 格**：貼在一起會讀成一台超寬的螢幕
    for mx in mons:
        cx = mx + mw // 2
        mbot = Y(height + stand, mon_d)          # 螢幕下緣 85
        mtop = mbot - mh + 1                     # 68

        # 底座：躺在桌面上，所以它的高度就是它的深度（往下畫幾列）。
        # **窄一點**：第一版 11 格寬 7 格深，兩台在桌上就是兩塊黑板子
        rect(cx - 4, cx + 4, Y(height, mon_d - 2), Y(height, mon_d + 2), "z")
        rect(cx - 4, cx + 4, Y(height, mon_d - 2), Y(height, mon_d - 2), "X")
        rect(cx - 4, cx + 4, Y(height, mon_d + 2), Y(height, mon_d + 2), "o")
        # 頸子
        rect(cx - 2, cx + 2, mbot + 1, Y(height, mon_d) + 1, "z")
        rect(cx - 2, cx - 2, mbot + 1, Y(height, mon_d) + 1, "x")

        # 邊框。上緣亮一階（朝上的那條窄面），其餘是正面
        rect(mx, mx + mw - 1, mtop, mbot, "x")
        rect(mx, mx + mw - 1, mtop, mtop, "X")
        rect(mx, mx + mw - 1, mtop - 1, mtop - 1, "o")
        rect(mx, mx + mw - 1, mbot, mbot, "o")
        rect(mx - 1, mx - 1, mtop - 1, mbot, "o")
        rect(mx + mw, mx + mw, mtop - 1, mbot, "o")

    blit(PLAYER, mons[0] + bez, Y(height + stand, mon_d) - mh + 1 + bez)
    blit(CRITTER, mons[1] + bez, Y(height + stand, mon_d) - mh + 1 + bez)

    # 鍵盤。明陽指定黑色，所以它是全房間唯一一塊大面積的 o——
    # 而 o 是描邊色，一整塊鋪下去會跟描邊糊在一起。**鍵帽用 z 撐出格子**，
    # 沒有那些格子它就是桌面上一個黑色的長方形
    kb_x0, kb_x1 = 21, 50
    kb_back, kb_front = Y(height + 2, 10), Y(height + 2, 14)
    rect(kb_x0, kb_x1, kb_back, kb_front + 1, "o")
    rect(kb_x0, kb_x1, kb_back, kb_back, "x")            # 朝上的那條窄邊
    for ky in range(kb_back + 1, kb_front):
        for kx in range(kb_x0 + 1, kb_x1, 2):
            px(kx, ky, "z")
    # 空白鍵。少了它五排一樣的格子讀起來是散熱孔不是鍵盤
    rect(kb_x0 + 9, kb_x1 - 9, kb_front - 1, kb_front - 1, "z")

    # 左手邊那本闔著的筆記本。它本來是配重（滑鼠在右手邊，左邊空一大塊
    # 看起來像還沒搬進來），**桌燈進來之後那個位置歸桌燈了**，
    # 所以筆記本往右挪到鍵盤跟滑鼠中間那條縫，變成順手放著的東西。
    #
    # 第一版用麻色 P 畫成一疊紙，結果是桌上一條發亮的白棒子——P 的亮度 211，
    # 全房間第二亮，一擺上去整張桌子的重心就跑到它身上。改成青的封面
    # （跟被子、地毯、海報同一條線），亮度 95，看得見但不搶。
    nb_x = 9
    nb_back, nb_front = Y(height + 2, 11), Y(height + 2, 15)
    rect(nb_x, nb_x + 10, nb_back, nb_front + 1, "o")
    rect(nb_x + 1, nb_x + 9, nb_back + 1, nb_front - 1, "C")
    rect(nb_x + 1, nb_x + 9, nb_back + 1, nb_back + 1, "L")   # 封面朝光的那一條
    rect(nb_x + 1, nb_x + 9, nb_front, nb_front, "c")         # 側邊那疊紙的厚度

    # 滑鼠。右手邊，一樣是黑的。**四個角都收一格**——5x5 的方塊是一顆骰子，
    # 收了角才是一隻滑鼠
    ms_x, ms_y = kb_x1 + 4, Y(height + 2, 12)
    for i, (a, b) in enumerate(((1, 3), (0, 4), (0, 4), (0, 4), (1, 3))):
        rect(ms_x + a, ms_x + b, ms_y + i, ms_y + i, "o")
    rect(ms_x + 1, ms_x + 3, ms_y + 1, ms_y + 3, "z")
    px(ms_x + 2, ms_y + 1, "x")                          # 滾輪

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(DESK_H) for c in range(DESK_W)]


DESK_TILES = _desk()


# ---------------------------------------------------------------- 桌燈
#
# M3 第九件。站在書桌左端，**而且點得下去可以開關**（明陽要的，跟吊燈一樣）。
#
#
# 它為什麼是自己一個物件，不是畫在書桌裡
# --------------------------------------
#
# 因為熱區是照物件的格子生的。畫進 `desk` 裡的話，可以點的範圍就是整張
# 4x6 的桌子——點螢幕、點鍵盤、點桌腳全部會開關燈。
#
# 拆出來之後它只佔第 15 欄那一欄（16px，桌機 82px、手機 61px，
# 都過得了 44px 的下限）。代價是那一欄跟左螢幕重疊了幾格，
# 也就是專輯封面最左邊那幾格點下去會開燈——那是量出來能接受的最小值，
# 再往右挪螢幕就會被預設視角切到。
#
#
# 為什麼站在桌子左端不是右端
# --------------------------
#
# 點得到的東西不能擺在最外面那一兩欄：桌機左右各藏約 1.2 欄，
# 擺右端（第 18-19 欄）會有人永遠點不到。這條跟碗、逗貓棒當初是同一條。
#
#
# 為什麼它比螢幕高
# ----------------
#
# 燈罩要在螢幕上面才不會擋到畫面。這不是美感是幾何：燈罩下緣 y=61、
# 螢幕上緣 y=68——**差七列**，桌燈的高度就是被這幾列決定的。
# 桿子在 x246-248，兩台螢幕從 x249 才開始，所以它整根都露在外面，
# 一格都沒有壓到螢幕。
#
# 燈罩開口朝下，所以**看不到裡面**（吊燈立的那條規矩）。看得到的是
# 罩子下緣那條鐵皮的厚度（`u`/`U`），跟燈泡露出來的那一點點。

DESKLAMP_AT = (15, 3)
DESKLAMP_W, DESKLAMP_H = 1, 3

DESKLAMP_D = 5        # 擺在桌上往裡面第幾格
DESKLAMP_H_PX = 30    # 燈罩下緣離桌面多高


def _desklamp():
    """1x3 的桌燈。回傳 3 塊 16x16 的磚。"""
    W, H = DESKLAMP_W * 16, DESKLAMP_H * 16
    ox, off = DESKLAMP_AT[0] * 16, DESKLAMP_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        x -= ox
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('desklamp')

    def rect(a, b, c, d, ch):
        for y in range(c, d + 1):
            for x in range(min(a, b), max(a, b) + 1):
                px(x, y, ch)

    def Y(h, d=DESKLAMP_D):
        """桌燈站在桌面上，所以它的「地面」是 DESK_HEIGHT 那條線。"""
        return WALL_FOOT + d - DESK_HEIGHT - h

    cx = ox + 7                    # 桿子的中線 = 247（絕對座標）
    seat = Y(0)                    # 站在桌面上那一點 91
    rim = Y(DESKLAMP_H_PX)         # 燈罩下緣 61

    # 底座。躺在桌面上，所以它的高度就是它的深度（往下畫幾列）
    rect(cx - 5, cx + 5, Y(0, DESKLAMP_D - 3), seat + 1, "z")
    rect(cx - 5, cx + 5, Y(0, DESKLAMP_D - 3), Y(0, DESKLAMP_D - 3), "X")
    rect(cx - 5, cx + 5, seat + 1, seat + 1, "o")
    rect(cx - 4, cx + 6, seat + 2, seat + 2, "h")      # 投在桌面上的影

    # 桿子。**1 格會斷成兩道刮痕，3 格才是一根桿子**，中間那格留 x 當高光
    rect(cx - 1, cx + 1, rim + 4, seat, "z")
    rect(cx, cx, rim + 4, seat, "x")

    # 燈罩。一個往下開的梯形，左邊亮右邊暗（光從左上來）。
    # 罩子裡面看不到（吊燈那條），所以下緣那兩列是**鐵皮的厚度**不是內壁
    hws = [2, 3, 4, 5, 6]
    for k, hw in enumerate(hws):
        y = rim - len(hws) + 1 + k
        rect(cx - hw, cx + hw, y, y, "o")
        for x in range(cx - hw + 1, cx + hw):
            t = (x - (cx - hw)) / (2.0 * hw)
            px(x, y, "X" if t < 0.38 else ("x" if t < 0.70 else "z"))

    # 罩子下緣那條被燈泡打亮的鐵皮，跟吊燈同一套：越靠中間越亮
    for k, hw in enumerate((6, 5)):
        y = rim + k
        for x in range(cx - hw, cx + hw + 1):
            px(x, y, "U" if abs(x - cx) <= 2 else "u")
        px(cx - hw, y, "o")
        px(cx + hw, y, "o")

    # 燈泡露出來的那一點。掛在罩子外面，理由同吊燈
    for i, pat in enumerate(("oUUUo", "ouuuo")):
        for j, ch in enumerate(pat):
            px(cx - 2 + j, rim + 2 + i, ch)

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(DESKLAMP_H) for c in range(DESKLAMP_W)]


DESKLAMP_TILES = _desklamp()

# 桌燈的燈泡在哪。跟 LAMP_BULB 同一招：畫出來的燈泡跟光源不可能分家
