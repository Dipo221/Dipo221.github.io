#
# 房間到底能多大，不是挑一個 max-width 就決定的，是**高度**決定的。
# 房間是固定比例的，加寬就等於加高，而頁面上房間以外的東西已經吃掉一大半。
#
# 縮放規則**兩個裝置現在一樣了**（待辦第 15 項，2026-09-03）：
#
#   高度填滿，寬度溢出去用左右滑的。
#
# 這條原本只有手機用，是明陽想出來的，它把這題的變數整個換掉了：
