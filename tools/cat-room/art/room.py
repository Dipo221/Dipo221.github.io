# ---------------------------------------------------------------- 海報與層架
#
# M3 第四件（待辦第 14 項）。掛在床上方那面牆，第 3-4 欄。
#
# **海報跟層架是同一件物件，不是兩件。** 它們的位置互相決定——層架往下挪一格
# 海報就得跟著挪，兩個分開的話那條關係只存在於誰的腦袋裡。而且它們合起來
# 才是一件東西：牆上那一組。
#
# 為什麼掛在床上面：那是這面牆唯一剩下、而且**不會跟衣櫃書桌搶**的地方。
# 第 15-18 欄的二選一還沒決定，海報掛過去會把牆的上半段吃掉——
# 書桌矮、上面還放得下海報，衣櫃高、放不下，等於替明陽把選擇做掉了。
#
# 第 3 欄不是第 1 欄：斜屋簷在第 1 欄只留第 4-5 列、第 2 欄只留第 3-5 列，
# 海報頂端在 y=33（第 2 列）擺過去會穿出屋頂。這條跟床當初一模一樣。
#
# 海報上畫的是**植物**，不是月亮也不是貓。貓會被讀成第二隻貓；
# 而植物讓它跟書櫃頂上那盆變成同一個房間裡的兩件事——
# 一張畫葉子的畫掛在一盆真的植物旁邊，那是一個有偏好的人，不是隨機的裝飾。

POSTER_AT = (3, 2)
POSTER_W, POSTER_H = 2, 3


def _poster():
    """2x3 的海報與層架。回傳 6 塊 16x16 的磚。"""
    depth = 4        # 層架從牆上凸出來多少
    # 板面離地多高。**42 會讓托架的最後一列掉到格子外面被靜靜切掉**——
    # 托架三列，最後一列落在 y=80，而這個物件只到 y=79。跟書櫃頂板當初一樣，
    # 切掉不會報錯，只會變成兩塊少一角的托架
    ledge_h = 44
    board = 3        # 板子多厚
    pw, ph = 20, 22  # 海報連框多寬多高

    W, H = POSTER_W * 16, POSTER_H * 16
    off = POSTER_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('poster')

    def rect(x0, x1, y0, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                px(x, y, ch)

    def Y(h, d=None):
        return WALL_FOOT + (depth if d is None else d) - h

    cx = W // 2
    ptop = 33
    px0, px1 = cx - pw // 2, cx - pw // 2 + pw - 1   # 6, 25
    pbot = ptop + ph - 1                             # 54

    # 框。外描邊 + 一圈木頭 —— 木框的頂面在上緣（受光），底下那條是背光的側面。
    # 少了這一階，框會變成一條畫在牆上的線而不是一個掛著的東西
    rect(px0, px1, ptop, pbot, "o")
    rect(px0 + 1, px1 - 1, ptop + 1, pbot - 1, "w")
    rect(px0 + 1, px1 - 1, ptop + 1, ptop + 1, "W")
    rect(px0 + 1, px1 - 1, pbot - 1, pbot - 1, "j")
    rect(px0 + 2, px1 - 2, ptop + 2, pbot - 2, "o")

    # 紙。淺色的底 —— 一面暗磚牆上要跳出來的是紙不是框
    ix0, ix1 = px0 + 3, px1 - 3      # 9 .. 22
    iy0, iy1 = ptop + 3, pbot - 3    # 36 .. 51
    rect(ix0, ix1, iy0, iy1, "p")
    rect(ix0, ix1, iy0, iy0, "P")    # 紙的上緣受光

    # 葉子。**一片大的，不是一叢小的。**
    #
    # 第一版是「一根莖 + 三對葉」，算出來是一堆散在紙上的短線——
    # 每一片葉只有 5 格長 1 格厚，那個尺寸畫不出葉子，只畫得出筆畫。
    # 14x16 的紙上只放得下一件東西，那就讓它是一整片。
    #
    # 立體感靠**左右分階**不是靠描邊：左半 G、右半 g，兩半交界那一條就是主脈，
    # 不用另外畫。外緣用 e 不用 o——版畫的葉緣是深綠的，
    # 描一圈黑會變成貼紙。
    stem = (ix0 + ix1) // 2
    hws = [0, 1, 2, 3, 4, 4, 5, 5, 5, 4, 4, 3, 1]
    for k, hw in enumerate(hws):
        y = iy0 + 1 + k
        for x in range(stem - hw, stem + hw + 1):
            px(x, y, "G" if x < stem else "g")
        px(stem - hw, y, "e")
        px(stem + hw, y, "e")
        px(stem, y, "e")                       # 主脈
    rect(stem, stem, iy0 + 1 + len(hws), iy1 - 1, "e")   # 葉柄

    # 層架。跟床架同一套：頂面 -> 分面線 -> 正面
    lback, lfront = Y(ledge_h, 0), Y(ledge_h)   # 70, 74
    lx0, lx1 = 2, W - 3
    rect(lx0, lx1, lback, lfront, "W")
    rect(lx0, lx1, lback, lback, "o")
    rect(lx0, lx1, lback + 1, lback + 1, "A")
    rect(lx0, lx1, lfront, lfront, "o")
    rect(lx0, lx1, lfront + 1, lfront + board, "w")
    rect(lx0, lx1, lfront + board, lfront + board, "o")
    rect(lx0, lx0, lback, lfront + board, "o")
    rect(lx1, lx1, lback, lfront + board, "o")
    # 托架。兩塊小三角撐在板子底下，沒有它板子是浮在牆上的
    for bx in (lx0 + 3, lx1 - 5):
        for i in range(3):
            rect(bx, bx + 2 - i, lfront + board + 1 + i, lfront + board + 1 + i, "j")

    # 板上的東西：左邊三本平放的書，右邊一本靠著的
    base = lback + 2
    for i, ink in enumerate(("C", "b", "G")):
        y = base - i * 2
        rect(lx0 + 3, lx0 + 11, y - 1, y, ink)
        rect(lx0 + 3, lx0 + 11, y - 1, y - 1, "o")
    rect(lx0 + 3, lx0 + 11, base + 1, base + 1, "o")
    rect(lx1 - 8, lx1 - 5, base - 8, base, "g")
    rect(lx1 - 8, lx1 - 5, base - 8, base - 8, "o")
    rect(lx1 - 5, lx1 - 5, base - 8, base, "o")

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(POSTER_H) for c in range(POSTER_W)]


POSTER_TILES = _poster()


# ---------------------------------------------------------------- 地毯
#
# M3 第五件（待辦第 14 項）。鋪在床跟書櫃中間那片空地板上，第 5-11 欄。
#
# 躺著的東西沒有面
# ----------------
#
# 前面每一件家具都在講「頂面最亮、正面中間、側面最暗」。地毯**一個面都沒有**
# ——它厚度是零，就是地板上的一塊形狀。所以它不用那條式子，也沒有落地的影：
# 它本來就貼在地上，沒有底下可以暗。
#
# 那也是它最容易畫壞的地方：一塊沒有面的矩形色塊在木地板上，讀起來會是
# 「地板破了一個洞」而不是「地上鋪了一塊布」。**流蘇是最強的訊號**，
# 因為只有織物會在兩端散開成一根一根的。有了流蘇，中間那塊才會被讀成布。
#
# 顏色被貓夾死了
# --------------
#
# 這是全房間唯一一件**躺在貓底下的大東西**，所以它直接受那條亮度差 lint 管：
# 地毯佔地板帶子的 18%，遠超過 10% 的門檻，一定會被量到。
#
# 可用的區間很窄：貓身上主色亮度 117.4，要差 30 階以上，所以地毯的主色
# 要嘛低於 87 要嘛高於 147。高於 147 的地板在一間閣樓裡不成立，
# 所以只剩「暗」這條路——但暗到跟地板（64.3）一樣就看不見地毯了。
#
# 解法是**靠色相不是靠亮度**：`c` 的亮度 68.4 跟地板幾乎一樣，但它是青的，
# 在一片暖棕裡自己就分得出來。對貓則有 49 階的差，安全得很。
# 順帶跟被子、海報連成同一條青色的線——一件青的東西是意外，三件是品味。
#
# **`C` 只能鋪窄的邊**（亮度 95.1，對貓只有 22.3 階）。它現在佔地板帶子
# 不到 4%，過得了門檻；把它拿去鋪滿整塊地毯就會當場紅。這條 lint
# 2026-09-04 之前是看不到物件的，也就是說地毯是第一件真的被它擋著的東西。

RUG_AT = (5, 8)
RUG_W, RUG_H = 7, 3


def _rug():
    """7x3 的地毯。回傳 21 塊 16x16 的磚。"""
    x0, x1 = 8, 104          # 布的左右（局部座標）
    y0, y1 = 132, 168        # 布的上下（絕對座標）
    band, gap = 3, 2         # 邊飾多寬、邊飾離布邊多遠
    fringe = 4               # 流蘇多長

    W, H = RUG_W * 16, RUG_H * 16
    off = RUG_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('rug')

    def rect(a, b, c, d, ch):
        for y in range(c, d + 1):
            for x in range(min(a, b), max(a, b) + 1):
                px(x, y, ch)

    # 布。四角各收一格——直角的矩形讀起來是一張紙，收了角才是一塊布
    for y in range(y0, y1 + 1):
        cut = 1 if y in (y0, y1) else 0
        rect(x0 + cut, x1 - cut, y, y, "c")

    # 邊飾。**只有這一圈可以用 C**，理由在上面那段
    for k in range(band):
        y = y0 + gap + k
        rect(x0 + gap, x1 - gap, y, y, "C")
        rect(x0 + gap, x1 - gap, y1 - gap - k, y1 - gap - k, "C")
    for k in range(band):
        x = x0 + gap + k
        rect(x, x, y0 + gap, y1 - gap, "C")
        rect(x1 - gap - k, x1 - gap - k, y0 + gap, y1 - gap, "C")

    # 中間那排菱形，加上下兩條細線。沒有它中間會是全房間最大的一塊平色
    mid = (y0 + y1) // 2
    for dy in (-7, 7):
        rect(x0 + 10, x1 - 10, mid + dy, mid + dy, "C")
    for cxx in range(x0 + 18, x1 - 14, 26):
        for k, hw in enumerate((1, 3, 5, 3, 1)):
            rect(cxx - hw, cxx + hw, mid - 2 + k, mid - 2 + k, "L")
        px(cxx, mid, "p")

    # 流蘇。兩端散開，三格一根。**這是「這是一塊布」唯一的證據**
    for y in range(y0 + 2, y1 - 1, 3):
        rect(x0 - fringe, x0 - 1, y, y, "p")
        rect(x1 + 1, x1 + fringe, y, y, "p")

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(RUG_H) for c in range(RUG_W)]


RUG_TILES = _rug()


# ---------------------------------------------------------------- 盆栽
#
# M3 第六件（待辦第 14 項）。**站在書櫃頂上**，那塊頂面畫書櫃的時候就是為它留空的。
#
# 它是唯一一件不站在地板、也不掛在牆上的家具——它站在**另一件家具上面**。
# 所以它的「地面」不是 WALL_FOOT，是書櫃頂面那條線：後緣 y=42、前緣 y=52
# （書櫃深 10）。盆底放在深度 7，也就是 y=49，往前留 3 格才不會像擺在懸崖邊。
#
# 高度被上下夾死：樑底在 y=28，盆底在 y=49，中間只有 21 格。所以它是一盆矮的、
# 圓的植物，不是一株細長往上長的——**這不是造型選擇，是這個位置只塞得下這一種**。
# 想要細長的就得放地上，而地上的欄位正是還沒決定的那件事。
#
# 葉子用三階綠（`e`/`g`/`G`）。第三階是海報那片葉子帶進來的，這裡直接受惠：
# 兩階的葉叢在 19 格寬的尺度上會是一坨平的綠。

PLANT_AT = (12, 1)
PLANT_W, PLANT_H = 2, 3


def _plant():
    """2x3 的盆栽。回傳 6 塊 16x16 的磚。"""
    seat = 42 + 7        # 書櫃頂面深度 7 那條線 = 盆底
    pot_h = 9            # 盆多高
    rim = 3              # 盆口那圈多厚
    # 每一片葉往哪裡長（相對盆口中央）。**六片，不是一叢。**
    #
    # 第一版是「一列一列給半徑」的葉叢，算出來是一個飛碟：一片扁透鏡浮在盆上、
    # 頂上還插著四根像天線的葉尖。那個做法在這個尺度上不成立——一叢葉子的輪廓
    # 是靠**葉跟葉之間的縫**讀出來的，用一個外框把它們圍起來就沒有縫了。
    #
    # 改成一片一片從盆口長出去，縫是自然留下來的。最高那片到 y=29，
    # 樑底在 y=28——這盆能長多高是樑決定的，不是我決定的。
    leaves = ((-9, -3), (-6, -8), (-1, -11), (4, -9), (8, -4))

    W, H = PLANT_W * 16, PLANT_H * 16
    off = PLANT_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('plant')

    def rect(a, b, c, d, ch):
        for y in range(c, d + 1):
            for x in range(min(a, b), max(a, b) + 1):
                px(x, y, ch)

    cx = 14                              # 偏左一點，不是書櫃頂的正中間——
    top = seat - pot_h                   # 擺正中間會像一個被人擺好的展示品
    base = top                           # 葉子從盆口長出來

    # 葉子。每一片是一條從盆口走出去的線，中段最厚、兩端收成一格——
    # 等寬的線是一根草，有腰身的才是一片葉。
    #
    # **描邊只描葉尖跟主脈，不描整片。** 第一版每一格都往兩側補 e，
    # 結果 th=1 的那幾段 3 格寬有 2 格是描邊，整叢葉子暗成一團——
    # 這個尺寸的葉子沒有描邊的預算，輪廓要靠葉跟葉之間的縫。
    for dx, dy in leaves:
        ink = "G" if dx < 0 else "g"     # 光從左上來
        n = max(abs(dx), abs(dy))
        for i in range(n + 1):
            t = i / float(n)
            x = int(round(cx + dx * t))
            y = int(round(base + dy * t))
            th = 0 if t < 0.16 else (1 if t < 0.34 else (2 if t < 0.78 else 1))
            rect(x - th, x + th, y, y, ink)
            if t >= 0.94:
                px(x, y, "e")            # 葉尖
            elif 0.3 < t < 0.8:
                px(x, y, "e")            # 主脈

    # 補洞。兩片葉子擦身而過的時候會留下**單獨一格**透明——那不是葉子之間的縫，
    # 是一個破洞，透出來的是磚牆。縫要兩格以上才讀得出來是縫，
    # 一格寬的只會被讀成一顆雜訊。補的顏色抄上面那一格，才不會在葉面上多一階
    for y in range(1, H - 1):
        for x in range(1, W - 1):
            if g[y][x] == "." and all(g[y + dy][x + dx] != "."
                                      for dy in (-1, 0, 1) for dx in (-1, 0, 1)
                                      if dy or dx):
                g[y][x] = g[y - 1][x]

    # 盆。上寬下窄，盆口那圈比盆身再寬一格
    for y in range(top, seat + 1):
        t = (y - top - rim) / float(pot_h - rim) if y > top + rim else 0.0
        hw = 8 - (0 if y <= top + rim else 1) - int(round(2 * t))
        rect(cx - hw, cx + hw, y, y, "p")
        rect(cx - hw + 1, cx - hw + 2, y, y, "P")     # 受光的那一側
        px(cx + hw - 1, y, "m")                       # 背光的那一緣
        px(cx - hw, y, "o")
        px(cx + hw, y, "o")
    rect(cx - 8, cx + 8, top, top, "o")               # 盆口
    rect(cx - 7, cx + 7, top + 1, top + 1, "P")
    rect(cx - 7, cx + 7, top + rim, top + rim, "o")   # 盆口下緣那條分面線
    rect(cx - 6, cx + 6, seat, seat, "o")             # 落在櫃頂上那條

    # 投在櫃頂上的影。光從左上來，所以影子往右下
    rect(cx + 3, cx + 9, seat + 1, seat + 1, "j")
    rect(cx + 4, cx + 8, seat + 2, seat + 2, "j")

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(PLANT_H) for c in range(PLANT_W)]


PLANT_TILES = _plant()


# ---------------------------------------------------------------- 紙箱
#
# M3 第七件（待辦第 14 項），而且它同時是**待辦第 17 項的前提**：
# Disi 叼回來的禮物收在這個箱子裡，點開才看得到。
#
# 所以它不是一件裝飾，是一顆按鈕。畫的時候只有一個問題要回答：
# **看不看得出來它可以打開？**
#
#
# 為什麼它可以插在那個二選一前面畫
# --------------------------------
#
# 衣櫃跟書桌都要靠牆站，右邊剩下的欄位擠不下兩件，那個決定還沒下。
# 紙箱矮，而且**不靠牆**——它站在地板中段，牆的那幾列一格都不吃。
#
# 吉他同樣不依賴那個決定，但它靠牆立著，會咬掉第 15-19 欄裡的一兩欄。
# 紙箱擺第 12-14 欄，那塊是地毯右緣（x188）到碗（x256）中間的空地板，
# 早就定案了——它填的不是還在爭的那塊地。
#
#
# 開口朝上，所以裡面看得到
# ------------------------
#
# 吊燈立過一條規矩：**開口朝下的東西看不到裡面**（見 _lamp()）。
# 紙箱是那條的反面，而且是同一個理由——這個投影由上往下看，
# 所以朝上的開口不但看得到，還是這件家具最大的一塊面（24x8，佔頂面一半以上）。
#
# 那個洞是這個箱子最重要的東西。沒有它，這就是一個淺色的方塊；
# 有了它，「可以放東西進去」不用任何一個字就講完了。
#
#
# 兩個畫不出來的細節，記在這裡免得下次再試
# ----------------------------------------
#
# 1. **瓦楞的斷面。** 紙板之所以是紙板就在切口那排波浪，但切口只有 2px 寬，
#    在上面做明暗交替只會得到一排雜訊——那不是瓦楞，是髒點。
# 2. **四片蓋全部攤平。** 前蓋攤平會蓋掉正面最上面那幾列，四片一起攤開
#    是「back 6 + 頂面 13 + front 6 + 正面 12」共 37 列，還要加落地的影，
#    3 格高（48px）塞不下。所以只攤左右後三片，前蓋改成**垂下來蓋在正面上**
#    ——真的開箱本來就常常是這樣，而且它順便把 30x19 那片平色切開。

BOX_AT = (12, 8)
BOX_W, BOX_H = 3, 3


def _box():
    """3x3 的紙箱。回傳 9 塊 16x16 的磚。"""
    dback, dfront = 43, 56   # 箱子的後緣、前緣往房間裡走多遠
    height = 15              # 多高。貓 24px，所以坐進去頭會露出來
    wall = 2                 # 紙板多厚 —— 頂面那圈切口就是這個厚度
    # 左右兩片蓋各自往外翹多少、多長、末端縮多少。**兩邊不一樣是刻意的**
    wings = ((5, 6, 2), (3, 5, 1))

    W, H = BOX_W * 16, BOX_H * 16
    off = BOX_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('box')

    def rect(a, b, c, d, ch):
        for y in range(c, d + 1):
            for x in range(min(a, b), max(a, b) + 1):
                px(x, y, ch)

    def Y(h, d):
        """就是那條式子。箱子不靠牆，所以前後緣兩個深度都要自己給。"""
        return WALL_FOOT + d - h

    # 箱身的左右。**左邊只能從第 7 欄起跳**：左蓋翹出去 6 格再加一格描邊
    # 就是 7，x0 給 6 的話最外面那條描邊會掉到格子外面被靜靜切掉（lint_clip 抓到過）
    x0, x1 = 7, 41
    tback, tfront = Y(height, dback), Y(height, dfront)   # 140, 153
    foot = Y(0, dfront)                                   # 168

    # 落地的影。先畫，讓箱子壓在它上面。跟床、書櫃同一個道理：
    # 沒有這一塊它就是一張貼在地板上的圖
    rect(x0 + 1, x1 - 1, foot + 1, foot + 2, "h")
    rect(x0 + 2, x1 - 2, foot + 3, foot + 3, "k")

    # 左右兩片蓋。**這兩片是側影上唯一說「它是開的」的東西**——
    # 只看正面的話，開著跟關著的箱子輪廓一模一樣。
    #
    # 第一版把它們畫成攤平的長方形，結果是箱子兩邊各貼一塊板子，
    # 整件東西讀起來是一台洗衣機不是一個紙箱。**要翹起來、而且要往末端收窄**：
    # 一片被折開的紙板不會是平的，也不會是方的。兩邊角度還要不一樣——
    # 對稱的兩片翼是機器，不是被貓拆過的箱子。
    #
    for side, (lift, span, taper) in zip((-1, 1), wings):
        edge = x0 if side < 0 else x1
        for i in range(1, span + 1):
            k = i / float(span)
            x = edge + side * i
            a = tback + 1 - int(round(lift * k))
            b = tfront - 1 - int(round(lift * k)) - int(round(taper * k))
            rect(x, x, a, b, "Q")
            px(x, b, "q")                  # near 那一緣落一階，蓋才有厚度
            px(x, a - 1, "o")
            px(x, b + 1, "o")
        rect(edge + side * (span + 1), edge + side * (span + 1),
             tback - lift, tfront - lift - taper, "o")

    # 頂面：一圈紙板的厚度，中間是開口
    rect(x0, x1, tback, tfront, "o")
    rect(x0 + 1, x1 - 1, tback + 1, tfront - 1, "Q")
    rect(x0 + 1, x1 - 1, tfront - 1, tfront - 1, "q")   # 近的那條切口背著光

    # 開口。上面三列亮一階是**內側後壁**，光從上面落進去只照得到那一片；
    # 再往下是箱底，照不到。兩階就夠了——這個洞要暗，暗才是深
    ix0, ix1 = x0 + 1 + wall, x1 - 1 - wall            # 12 .. 35
    iy0, iy1 = tback + 1 + wall, tfront - 1 - wall     # 139 .. 146
    rect(ix0, ix1, iy0 - 1, iy1, "o")
    rect(ix0, ix1, iy0, iy1, "h")
    rect(ix0, ix1, iy0, iy0 + 2, "k")

    # 正面。比朝上的面暗一階 —— 這是這個房間每一件家具都在用的規矩。
    #
    # **這一整組色是被貓挑掉的，不是挑好看的。** 先畫的那一版朝上用 q、
    # 正面用 t，看起來比較沉穩，但 t 的亮度是 101、貓身上主色 117——
    # 貓走到箱子前面就整隻融進去了。要跟貓拉開 30 階，正面只能低於 87
    # 或高於 147；一個暗到 87 以下的紙箱不存在，所以只剩 q(157) 這一條路，
    # 朝上的面跟著被推到 Q。lint 只量地板量不到這件事，但道理是同一條
    rect(x0, x1, tfront, foot, "q")
    rect(x0, x1, tfront, tfront, "o")                  # 頂面轉到正面
    rect(x0, x0, tfront, foot, "o")
    rect(x1, x1, tfront, foot, "o")
    rect(x0, x1, foot, foot, "o")
    rect(x0 + 1, x1 - 1, foot - 2, foot - 1, "t")      # 貼著地板那兩列暗下來

    # 正面上的兩樣東西。**一橫一豎都不行，斜的才行**：
    # 第一版在正面中間拉了一條橫的摺線，那條線把正面切成上下兩塊，
    # 整個箱子當場變成一個兩層的抽屜櫃，摺痕還剛好長得像抽屜的把手。
    # 橫線在傢俱上的意思是「這裡會拉開」，紙箱身上不能有。
    #
    # 1. 一道斜的凹痕。斜線讀不成任何一種傢俱的構造，只讀得成「這裡被壓過」。
    #    **一條暗線不夠**，那是一根頭髮；凹痕要有暗的谷配一條亮的稜，
    #    兩條並排才是紙板被壓出來的摺
    for i in range(7):
        px(x0 + 5 + i, tfront + 4 + i, "t")
        px(x0 + 6 + i, tfront + 4 + i, "Q")
    # 2. 一張貼歪的標籤。它是這個箱子唯一在說「它從別的地方來」的東西，
    #    而且順便把 35x15 那片平色切開。歪一格是重點，貼正的標籤是印刷
    lx, ly = x1 - 14, tfront + 5
    rect(lx, lx + 9, ly, ly + 6, "o")
    rect(lx + 1, lx + 8, ly + 1, ly + 5, "Q")
    rect(lx + 2, lx + 7, ly + 2, ly + 2, "t")
    rect(lx + 2, lx + 6, ly + 4, ly + 4, "t")
    px(lx + 9, ly + 1, "q")                            # 右下角翹起來一點

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(BOX_H) for c in range(BOX_W)]


BOX_TILES = _box()


# ---------------------------------------------------------------- 書桌與雙螢幕
