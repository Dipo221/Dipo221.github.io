# ---------------------------------------------------------------- 吉他
#
# M3 最後一件，也是清單上最後一件。靠在書櫃左邊，第 11-12 欄。
#
#
# 第一版放在空牆中間，那是「放得下」不是「該放」
# ----------------------------------------------
#
# 第一版擺在逗貓棒跟窗中間那面空牆上（第 7-8 欄），挑那裡的理由是量出來的：
# 逗貓棒最右邊在 x=109、窗畫出來的左緣在 x=136，那是房間最後一塊放得下的牆。
#
# **但放得下不等於該放。** 那面牆的正下方是地毯，於是那把琴變成房間裡
# 唯一一件誰都不挨著的東西——其他九件不是靠牆就是站在別人上面，
# 只有它自己立在空地毯中間。突兀的是這個，不是畫工。
#
# 靠到書櫃旁邊就成立了：琴身最寬那幾列（y118-122）壓在書櫃的左框上，
# 琴底站在書櫃前面那條空地板（y=128，深度 16）。
# **一把靠著的琴必須真的碰到它靠的東西**，差一格就變成一把正在倒下去的琴。
#
#
# 「再小一點」小多少：兩把尺量到同一個數字
# ----------------------------------------
#
#     書櫃高 70 格 = 一個 180cm 的書櫃   ->  2.57 cm/格
#     書桌高 26 格 = 一張 75cm 的書桌    ->  2.88 cm/格
#
# 一把 104cm 的吉他在這兩把尺下是 36 到 40 格。現在畫的是 41 格。
#
# 第一版 51 格，換算是 130cm——那不是吉他的長度。而且 51x17 的比例是 1:3.0，
# 真吉他大約 1:2.6：**縮短不只是變小，是順手把比例修對**。現在 41x15 = 1:2.7。
# （上一版這裡寫「17x50 剛好落在 1:2.6」，那句是算錯的，50/17 = 2.9。）
#
#
# 它是往書櫃的**反方向**倒的，那不是畫錯
# --------------------------------------
#
# 直覺的畫法是往書櫃那邊斜、琴頭壓上去。試過，不能用，而且是被兩件事夾死的：
#
#   斜度小：琴身比琴頭寬 8 格，所以琴頭還沒碰到書櫃、琴身就先貼上去了。
#           **琴頸會變成一條跟書櫃左框平行、只隔一兩格的深色線**——
#           指板是深的、框也是深的，兩條併在一起就糊成書櫃自己的一根柱子。
#   斜度大：琴頸改成斜切過書櫃，不平行了，但 0.45 的斜度在 41 格上
#           每兩列就要跳一格，那條琴頸讀起來是一條拉鍊。
#
# 所以改成琴底挨著書櫃、琴身往左倒（lean 是負的）。琴頸因此走在乾淨的磚牆上，
# 離書櫃 6 格遠，兩條深色的東西不再並排。**接觸點從琴頭換成琴身**，
# 而琴身是淺色的，壓在深色的框上一眼就看得出來誰在前面。
#
# 斜度只有 -0.12（41 列偏 5 格，約 7 度）：這個尺寸的琴頸只有 5 格寬，
# 再斜一點階梯就看得出來了。
#
#
# 為什麼是淺色的琴
# ----------------
#
# 換了位置這條沒變，因為決定它的一直是貓不是牆。琴身橫跨牆（磚 L100）、
# 踢腳板（L100）和地板（L64），三種背景；而貓會走到它前面
# （琴底在第 8.0 列，貓走得到 7.5-10.9）。現在還多一個：書櫃的框（L40 上下）。
#
# 暗色的琴（`j` L66）在牆上看得見，但在地板上會整個消失。
# 中間調的 `W`（L130）跟貓身上主色（117.4）只差 13——貓站在琴前面就融進去了。
# 剩下的只有 `A`（L158）：對貓差 41、對三種背景都差 58 以上。
# **一把淺色雲杉面板的吉他不是造型選擇，是唯一過得了那兩條的選項。**
#
#
# 弦只畫在指板上
# --------------
#
# 六條弦在 5 格寬的琴頸上畫不出來。畫得出來的是「深色指板上有兩條亮線」，
# 那就夠讀成弦了；而同樣兩條線畫在淺色的面板上會消失
# （`p` 對 `A` 幾乎同亮度）。**所以弦到琴身就停**——
# 那不是偷懶，是這個尺寸下唯一讀得出來的畫法。

GUITAR_AT = (11, 5)
GUITAR_W, GUITAR_H = 2, 4


def _guitar():
    """2x4 的吉他。回傳 8 塊 16x16 的磚。"""
    bottom, top = 128, 88        # 琴底落地（深度 16）、琴頭頂端（絕對 y）
    lean = -0.12                 # 每往上一列往右偏幾格。0 = 直挺挺插在地上
    base = 189                   # 琴底的中線
    # 琴身的半寬，由下往上一列一個。下寬上窄、中間收腰——
    # **腰是吉他之所以是吉他**，少了它那是一支球拍
    # **上下兩個腰身的比例是這裡的重點**：下腰最寬 7、上腰最寬 5（1.4 比 1）。
    #
    # **琴身自己的長寬比才是「這是不是吉他」的那一條。** 第一次縮小畫成
    # 15 寬 17 高（1.13，幾乎是正方形），整把讀成烏克麗麗——烏克麗麗跟吉他
    # 差的正是這個，不是大小。舊版 17 寬 25 高是 1.47，這裡 15 寬 21 高
    # 是 1.40，那條沒動。琴身一佔全長的一半，總長就跟著定死在 41 格。
    hws = [4, 6, 7, 7, 7, 7, 7, 7, 7, 6, 5, 4, 4, 3, 4, 5, 5, 5, 5, 4, 3]
    neck_hw = 2
    head_hw = 3

    W, H = GUITAR_W * 16, GUITAR_H * 16
    ox, off = GUITAR_AT[0] * 16, GUITAR_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        x -= ox
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('guitar')

    def rect(a, b, c, d, ch):
        for y in range(c, d + 1):
            for x in range(min(a, b), max(a, b) + 1):
                px(x, y, ch)

    def cx(y):
        """這一列的中線。往上走會往右偏，那就是「靠著」的全部訊息。"""
        return base + int(round((bottom - y) * lean))

    body_top = bottom - len(hws) + 1        # 108
    head_bot = top + 5                      # 93

    # 落在地板上那道影。先畫，讓琴壓在上面。**只有一列**——
    # 兩列以上會讀成琴架，而它是靠著書櫃不是站在架子上
    rect(cx(bottom) - 6, cx(bottom) + 7, bottom + 1, bottom + 1, "h")

    # 琴頸與指板。指板是深的，弦才有地方可以亮
    for y in range(head_bot, body_top + 3):
        c = cx(y)
        rect(c - neck_hw, c + neck_hw, y, y, "o")
        rect(c - neck_hw + 1, c + neck_hw - 1, y, y, "k")
    # 弦：兩條，只走指板。三條會把 3 格寬的指板填滿，那是一塊亮板不是弦
    for dx in (-1, 1):
        for y in range(head_bot + 1, body_top + 2):
            px(cx(y) + dx, y, "p")
    # 品絲。每 4 列一條，指板才有長度感
    for y in range(head_bot + 3, body_top, 4):
        c = cx(y)
        rect(c - 1, c + 1, y, y, "X")

    # 琴頭。比琴頸寬，兩側各兩顆弦鈕。
    # **弦鈕要用 cx(top) 不是 cx(y)**：琴頭是一塊直的板，整塊照 cx(top) 畫的；
    # 用 cx(y) 的話斜度會讓弦鈕掉到板子裡面去（斜度 0.09 時只差 1 格看不出來，
    # 0.30 就差 2 格了）
    rect(cx(top) - head_hw, cx(top) + head_hw, top, head_bot, "o")
    rect(cx(top) - head_hw + 1, cx(top) + head_hw - 1, top + 1, head_bot - 1, "j")
    for y in (top + 2, top + 4):
        px(cx(top) - head_hw, y, "X")
        px(cx(top) + head_hw, y, "X")

    # 琴身。一列一列照半寬畫，描邊在外、面板在內
    for i, hw in enumerate(hws):
        y = bottom - i
        c = cx(y)
        rect(c - hw, c + hw, y, y, "o")
        if hw > 1:
            rect(c - hw + 1, c + hw - 1, y, y, "A")
            # 右緣落一階：琴是圓的，光從左上來
            px(c + hw - 1, y, "W")
            if hw > 3:
                px(c + hw - 2, y, "W")

    # 音孔。位置在腰的下面一點，不是琴身正中間——正中間那是一個圓標。
    #
    # **要一格一格量半徑，不能一列一列拉矩形。** 第一版用 rect 拉，
    # 結果音孔上下各多出一條貫穿琴身的橫槓：那不是鑲邊，
    # 是「把整列填滿再把中間挖掉」留下來的兩隻手臂。
    #
    #
    # 半徑 2 就沒有「鑲邊」可以畫了：`o` 只到 1.6 的話核心是一塊 3x3 的方塊，
    # 外面那圈 `j` 反而把它撐成一個帶毛邊的方孔。所以**這個尺寸的音孔是
    # 一個純圓、沒有邊**。門檻是 2.3 不是 2.0：2.0 只收得到上下左右四格，
    # 畫出來是一個菱形；2.3 剛好多收四個斜角，變成一個切角的 5x5，那才是圓。
    sh_y, sh_r = 119, 2
    for dy in range(-sh_r, sh_r + 1):
        y = sh_y + dy
        c = cx(y)
        for dx in range(-sh_r, sh_r + 1):
            if (dx * dx + dy * dy) ** 0.5 <= sh_r + 0.3:
                px(c + dx, y, "o")

    # 琴橋。音孔下面那條，琴弦真正的終點。**只有琴身的三分之一寬**——
    # 拉到一半寬它就變成一張嘴，配上音孔那隻眼睛整把琴會變成一張臉
    by = sh_y + 5
    rect(cx(by) - 2, cx(by) + 2, by, by + 1, "j")
    rect(cx(by) - 2, cx(by) + 2, by, by, "k")

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(GUITAR_H) for c in range(GUITAR_W)]


GUITAR_TILES = _guitar()


