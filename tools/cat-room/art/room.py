SHELF_AT = (12, 2)
SHELF_W, SHELF_H = 3, 7


def _shelf_books(span, inks, seed):
    """一層書。**該挑的是規則，不是一本一本擺。**

    三層加起來四十幾本，手擺沒有意義：改一個隔板高度就要全部重排，
    而且「那本書為什麼在那裡」對每一本都沒有答案。所以這裡寫的是規則
    （2-3 格寬、9-13 格高、七分之一的機會留個縫），書自己排出來。
    換 seed 就重洗一次，換完是什麼樣子要算繪出來看。

    亂數是自己寫的 LCG 不是 `random`，因為這是**素材的一部分**——
    它必須在任何一台機器、任何一個 Python 版本上都產出同一排書。
    """
    rnd = seed & 0x7FFFFFFF

    def nxt(n):
        nonlocal rnd
        rnd = (rnd * 1103515245 + 12345) & 0x7FFFFFFF
        return (rnd >> 8) % n

    out, x = [], 0
    while x < span - 3:
        w = 2 + nxt(2)
        # 偶爾留一個縫。滿滿一排沒有縫的話那不是書，是一條條紋
        out.append(("", w, 0) if out and nxt(7) == 0
                   else (inks[nxt(len(inks))], w, 9 + nxt(5)))
        x += w
    return out


def _shelf():
    """3x7 的書櫃。回傳 21 塊 16x16 的磚（從左到右、從上到下）。"""
    depth = 10       # 櫃子往房間裡面佔多深
    H = 70           # 多高
    n = 4            # 切成幾格（最下面那格是關起來的櫃子）
    side = 4         # 側板多寬
    board = 3        # 隔板多厚
    over = 1         # 頂板比櫃身往外凸幾格
    inks = "LCpPbGg"  # 書背的顏色。青、麻、磚紅、綠 —— 沒有 q/Q

    W, Hpx = SHELF_W * 16, SHELF_H * 16
    off = SHELF_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(Hpx)]

    def px(x, y, ch):
        y -= off
        if 0 <= x < W and 0 <= y < Hpx:
            g[y][x] = ch
        else:
            _clip('shelf')

    def rect(x0, x1, y0, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                px(x, y, ch)

    def Y(h, d=None):
        return WALL_FOOT + (depth if d is None else d) - h

    tback, tfront = Y(H, 0), Y(H)       # 頂板的後緣 42、前緣 52
    foot = Y(0)                          # 落地 122

    # 頂板。跟床頭板同一套：一列一列算縮幾格，不是畫完再把角挖掉
    for y in range(tback, tfront + 1):
        cut = max(0, 2 - (y - tback))
        rect(cut, W - 1 - cut, y, y, "o")
        if y > tback:
            rect(cut + 1, W - 2 - cut, y, y, "A" if y == tback + 1 else "W")

    # 櫃身。比頂板窄 over 格，所以頂板看起來是蓋上去的
    cx0, cx1 = over, W - 1 - over
    rect(cx0, cx1, tfront, foot, "w")
    rect(cx0, cx0, tfront, foot, "o")
    rect(cx1, cx1, tfront, foot, "o")
    rect(cx0, cx1, foot, foot, "o")
    rect(cx0 + side - 1, cx0 + side - 1, tfront, foot, "o")   # 左側板的內緣
    rect(cx1 - side + 1, cx1 - side + 1, tfront, foot, "o")   # 右側板的內緣
    rect(cx0 + 1, cx0 + side - 2, tfront + 1, foot - 1, "w")
    rect(cx1 - side + 2, cx1 - 1, tfront + 1, foot - 1, "j")  # 右側板背光

    # 隔板。從上往下均分成 n 格
    ix0, ix1 = cx0 + side, cx1 - side
    inner_top, inner_bot = tfront + board, foot - board
    edges = [inner_top + round((inner_bot - inner_top) * i / n) for i in range(n + 1)]

    for i in range(n):
        y0, y1 = edges[i], edges[i + 1]
        rect(ix0, ix1, y0, y1, "h")                       # 櫃子裡面是暗的
        rect(ix0, ix1, y1 - board + 1, y1, "w")           # 這一層的板
        rect(ix0, ix1, y1 - board + 1, y1 - board + 1, "A")
        rect(ix0, ix1, y1, y1, "o")

        if i == n - 1:
            # 最下面那格關起來。**橫向的節奏被打斷一次**才有家具感——
            # 四層一模一樣的開放格是一張條紋，不是一個櫃子
            rect(ix0, ix1, y0 + 1, y1 - board, "w")
            rect(ix0, ix1, y0 + 1, y0 + 1, "o")
            mid = (ix0 + ix1) // 2
            rect(mid, mid, y0 + 2, y1 - board, "o")       # 兩片門中間的縫
            for dx in (mid - 3, mid + 3):
                rect(dx, dx, (y0 + y1) // 2, (y0 + y1) // 2 + 1, "o")   # 把手
            continue

        x = ix0 + 1
        for ch, bw, bh in _shelf_books(ix1 - ix0 - 2, inks, 7 + i * 31):
            if not ch:
                x += bw
                continue
            top = y1 - board - bh
            rect(x, x + bw - 1, top, y1 - board, ch)
            rect(x, x + bw - 1, top, top, "o")                   # 書的上緣
            rect(x + bw - 1, x + bw - 1, top, y1 - board, "o")   # 書背之間的縫
            x += bw

    # 落地的影。跟床同一個道理：沒有這一塊它就是浮的
    rect(cx0 + 1, cx1 - 1, foot + 1, foot + 2, "h")
    rect(cx0 + 2, cx1 - 2, foot + 3, foot + 3, "k")

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(SHELF_H) for c in range(SHELF_W)]


SHELF_TILES = _shelf()


# ---------------------------------------------------------------- 吊燈
#
# M3 第三件家具（待辦第 14 項）。掛在大樑上，第 6-7 欄，窗的左邊。
#
# 挑它是因為它**不吃地面欄位**。剩下要站在地上的大件（衣櫃、書桌）擠不進
# 剩下的第 15-18 欄，那個二選一還沒決定；吊燈掛在樑上，畫它不會把那四欄花掉。
#
#
# 吊著的東西深度只能是 0
# ----------------------
#
# 床和書櫃可以有深度（18 和 10），因為**地板是一條 64px 的帶子**——
# 站著的東西可以落在帶子裡面的任何一條線上，深度多少都有地方接。
#
# 天花板沒有那條帶子。這間房間只有一面牆和一片地板，樑是畫在**牆平面上**的。
# 所以繩子一往前吊，它的上端就會落在牆上某個沒有東西可以掛的高度——
# 一根從磚縫裡長出來的線。
#
# 所以吊燈的深度是 2，也就是樑自己的深度（樑的頂面 2px 高，那就是它的深度）。
# 它貼著牆吊，跟窗、跟踢腳板同一個平面。這不是將就，是這間房間的形狀
# 只允許這一個答案——**要讓燈真的吊進房間裡，得先有天花板那條帶子**，
# 那是另一間房間了。
#
# 順帶決定了它能垂多長：樑底畫在 y=28，地板在 y=112，中間只有 84px。
# 燈罩頂離地 72、下緣 61、燈泡最低 57，繩子露出來 11px。再長就會吊到
# 一個人走過去會撞到的高度——這間房間是閣樓，天花板本來就低。
#
#
# 燈罩裡面是看不到的
# ------------------
#
# 這個投影是**由上往下看**的：每一件東西都露出頂面，樑也是（見檔案開頭）。
# 那麼一個開口朝下的燈罩，看得到的就只有它的外面——裡面那圈被照亮的內壁、
# 罩子裡那顆燈泡，一格都看不到。
#
# 在燈罩下緣畫一條亮線當「裡面亮著」是最順手的做法，也是錯的：那條線
# 在這個投影裡沒有任何一個面對得上，等於在同一張圖裡混了第二種投影。
#
# 所以燈泡掛在燈罩**外面**。這是唯一誠實的做法，而且剛好就是工業吊燈
# 本來的樣子。燈罩最下面那一列是暖色的 `u`，那條不是內壁，是**鐵皮的厚度**——
# 它就在燈泡正上方，被下面那顆打亮是對的。

# 樑在第 1 列。繩子要從樑**畫出來的**底接下去，所以這個數字從 BEAM 自己算，
# 不要抄一個 28 進來——樑的排版改一列，繩子就會斷在半空中或穿進樑裡。
# 那兩條整列都是 o 的分別是分面線（第 7 列）和樑底（第 12 列），要的是下面那條
BEAM_ROW = 1
BEAM_FOOT = BEAM_ROW * 16 + max(i for i, r in enumerate(BEAM) if set(r) == {"o"})

LAMP_AT = (6, 1)
LAMP_W, LAMP_H = 2, 3

# 這三個放在函式外面，是因為**燈打出來的那道光要用同一組數字算光源在哪**
# （見下面 LAMP_BULB）。留在 _lamp() 裡面的話，燈泡的位置就會有兩個答案，
# 而光源錯一格是看不出來的——光暈本來就是糊的
LAMP_DEPTH = 2   # 跟樑同一個深度。理由在上面「吊著的東西深度只能是 0」
LAMP_HANG = 72   # 燈罩頂離地多高
LAMP_SH = 12     # 燈罩多高（含下緣翻出來的兩列）
LAMP_RIMS = (8, 9)   # 下緣的鐵皮往外翻出來那兩列的半徑


def _lamp():
    """2x3 的吊燈。回傳 6 塊 16x16 的磚（從左到右、從上到下）。"""
    depth, hang, sh = LAMP_DEPTH, LAMP_HANG, LAMP_SH
    # 半徑一列一列往外開。**越下面開得越快**——等差的話那是一個圓錐，
    # 加速的才是一個鐘形的燈罩
    hws = [3, 3, 4, 4, 5, 5, 6, 6, 7, 8]
    rims = LAMP_RIMS

    W, H = LAMP_W * 16, LAMP_H * 16
    off = LAMP_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('lamp')

    def rect(x0, x1, y0, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                px(x, y, ch)

    def Y(h, d=None):
        return WALL_FOOT + (depth if d is None else d) - h

    cx = W // 2                  # 燈的中線
    top = Y(hang)                # 燈罩頂           42
    rim = top + sh - len(rims)   # 下緣第一列       52
    sock = top - 2               # 線扣             40

    # 繩子。1px，從樑底一路接到線扣。**中間不准斷**——斷一格它就不是一條繩子，
    # 是牆上的兩道刮痕。它也是這盞燈唯一的「接地」：床和書櫃靠影子證明自己
    # 沒有浮著，吊燈靠的是這條線真的碰到樑
    rect(cx, cx, BEAM_FOOT + 1, sock - 1, "o")

    # 線扣：繩子跟燈罩中間的那顆五金。少了它繩子會直接插進燈罩，
    # 讀起來像一根釘子而不是吊起來的
    for y in range(sock, top):
        rect(cx - 2, cx + 2, y, y, "o")
        rect(cx - 1, cx - 1, y, y, "X")
        rect(cx, cx, y, y, "x")
        rect(cx + 1, cx + 1, y, y, "z")

    # 燈罩。左亮右暗是這個房間從窗就定死的「光從左上來」；
    # 罩子是圓的，所以那個轉折要橫著走完整整一排，不是只有邊緣一條
    for k, y in enumerate(range(top, rim)):
        hw = hws[k]
        rect(cx - hw, cx + hw, y, y, "o")
        for x in range(cx - hw + 1, cx + hw):
            t = (x - (cx - hw)) / (2.0 * hw)
            if k < 2:
                t -= 0.18            # 最上面兩列是朝上的面，整列亮一階
            px(x, y, "X" if t < 0.40 else ("x" if t < 0.72 else "z"))

    # 燈罩下緣。這兩列是**鐵皮的厚度**不是內壁（見上面那段），它就在燈泡正上方，
    # 所以是暖的、而且**越靠中間越亮**——光是從下面中央那顆打上來的。
    #
    # 這裡是這盞燈最大的一塊亮面（19px 寬，燈泡才 7px）。第一版整條都是同一個
    # `u`，夜裡那盞燈就只剩一個小點在發光，撐不起「暖房間的夜晚重點在燈」
    # 那句話。會發光的東西要看起來在發光，靠的是**亮的面積**不是最亮的那一階
    for k, hw in enumerate(rims):
        y = rim + k
        for x in range(cx - hw, cx + hw + 1):
            px(x, y, "U" if abs(x - cx) <= 3 else "u")
        px(cx - hw, y, "o")
        px(cx + hw, y, "o")

    # 燈泡。掛在燈罩外面，由上往下看看不到罩子裡面
    for i, (hw, pat) in enumerate(((2, "oUUUo"),
                                   (3, "oUUUUUo"),
                                   (3, "oUUUUUo"),
                                   (3, "ouUUUuo"),
                                   (2, "ouuuo"))):
        for j, ch in enumerate(pat):
            px(cx - hw + j, rim + len(rims) + i, ch)

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(LAMP_H) for c in range(LAMP_W)]


LAMP_TILES = _lamp()

# 燈泡的正中心，絕對座標。_lamp() 從同一組常數推出燈泡畫在哪，這裡再推一次，
# 所以「畫出來的燈泡」跟「光從哪裡射出來」不可能分家
LAMP_BULB = (LAMP_AT[0] * 16 + LAMP_W * 16 // 2,
             WALL_FOOT + LAMP_DEPTH - LAMP_HANG + LAMP_SH + 2)

