def _brick_var():
    """同一面牆裡顏色不一樣的兩塊磚。

    一面完全均勻的磚牆看起來像壁紙。挑兩塊換色就夠打破那個規律，
    而且因為只是換色不是換形狀，錯縫的相位不會被動到。
    """
    rows = [list(r) for r in BRICK]
    for y, ch in ((4, "b"), (5, "n"), (6, "n")):      # 第 1 層 x4-10：燒得比較深的一塊
        for x in range(4, 11):
            rows[y][x] = ch
    for y, ch in ((8, "B"), (9, "B"), (10, "b")):     # 第 2 層 x8-14：比較淺的一塊
        for x in range(8, 15):
            rows[y][x] = ch
    return ["".join(r) for r in rows]


