#
# 房間到底能多大，不是挑一個 max-width 就決定的，是**高度**決定的。
# 房間是固定比例的，加寬就等於加高，而頁面上房間以外的東西已經吃掉一大半。
#
# 縮放規則**兩個裝置現在一樣了**（待辦第 15 項，2026-09-03）：
#
#   高度填滿，寬度溢出去用左右滑的。
#
# 這條原本只有手機用，是明陽想出來的，它把這題的變數整個換掉了：
# 房間不必塞進 375px 之後，倍率由**列數**決定，欄數不再壓縮貓。
#
# 桌機以前是另一條規則——整間房間要看得完，不捲動，倍率取寬與高之中比較緊的
# 那個（等同 object-fit: contain）。滿版之後那條規則消失了：**20/11 比任何
# 一般螢幕都扁，填滿高度跟塞得下寬度不可能同時成立**，二選一。選了高度，
# 所以桌機左右也會溢出，也跟著貓捲（script.js 的 follow()，那支不用改，
# 它問的一直是「有沒有溢出」而不是「是不是手機」）。
