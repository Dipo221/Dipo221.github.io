# ---------------------------------------------------------------- 床
#
# M3 第一件家具（待辦第 14 項）。4 格寬、5 格高，擺在第 1 欄第 4 列，床頭在左。
#
#
# 這間房間的投影規則，整張床只有這一條式子
# ------------------------------------------
#
#     y = WALL_FOOT + 深度 - 高度
#
# WALL_FOOT 是踢腳板的底，也就是**地板深度 0** 那條線。「深度」是往房間裡面走多遠，
# 「高度」是離地多高——兩個都往上走，所以一個加一個減。
#
# 寫下這條式子是因為**上一版的床是浮的**。它的腳畫在 y=111，也就是牆跟地板的交界。
# 那條線在這個投影裡不是「地板的最裡面」，是**牆的最下面**——東西碰到那裡等於
# 掛在牆上，不是站在地上。地板是 y=112 到 175 這一整條 64px 的帶子，
# 站著的東西必須落在帶子**裡面**。
#
# 這條式子一寫出來，床浮不浮、佔多深、被子垂多長就都不用再用眼睛猜了。
# 它腳落地在 y=130，換算是第 8.4 列——貓走得到的範圍是 7.5 到 10.9，
# 所以貓可以從床後面走過去，也可以從床前面走過去。這是選這個深度的理由。
#
#
# 畫出來看了才改掉的五件事
# ------------------------
#
# 1. **要有木頭床架。** 第一版被子直接垂到地上，讀起來是一個青色的箱子。
#    被子只垂 drape=7px，下面露出木頭的床架，床才有內部構造，
#    也才跟房間裡其他的木頭是同一間房間的東西。
# 2. **床頭那一段只有頂面露床單。** 被子一路鋪到枕頭底下的話，整張床從頭到尾都是青的，
#    看起來像一張蓋布的長凳上放了個抱枕。但**垂下來那一面整條都是被子**——
#    真的鋪好的床，被子是蓋過整張的，只有頭那一段的頂面把被子折回去才露得出床單。
#    上一版連垂面也跟著分兩段，床頭那一塊的頂面和垂面就都是同一個 p，
#    中間只有一條線——那是一個紙盒，不是床。**每兩個面之間都要有一階亮度**，
#    這是這個檔案從踢腳板就在用的規矩（見色盤那段的 j/w/W）。
# 3. **床頭板要先畫，而且要比枕頭寬。** 最後畫的話它會從頂端一路通到地板，
#    那是一根柱子或一支煙囪。先畫、讓床架和枕頭壓在它前面，只露出床面以上那一段。
#    寬度掃過 9 和 13，**兩個都比枕頭窄**：枕頭從兩邊凸出去，剩下露在上面的那一塊
#    就變成一個掛在牆上的相框。現在跟床單那一段一樣寬（duv + 1）。
# 4. **褶不能是三條等距的直線**，那是「正」字的筆畫。改成兩條、不等距、
#    頂面上的斜著走——布皺起來本來就不會對齊。
# 5. **枕頭是亮的填色配暗的下緣**，不是暗的填色配亮的框。後者是一個相框。
# 6. **收角不可以先畫完再挖。** 「.」在這裡是透明，寫下去不是「收一個角」，
#    是**挖一個洞**：枕頭的角挖穿它底下的床單、床頭板的角挖穿它自己，
#    洞裡露出來的是磚牆。而且挖完會在角的外面留下一顆孤立的描邊點。
#    收角要先算「這一列縮幾格」再畫那一列，逗貓棒可以那樣挖是因為它後面沒有東西。
#
#
# 為什麼是第 1 欄不是第 0 欄
# --------------------------
#
# 屋簷是斜的：第 0 欄只有第 5 列是磚（第 4 列已經是 `<`），第 1 欄則是第 4-5 列。
# 床頭板頂端在 y=74，也就是第 4 列——擺在第 0 欄的話床頭板會**穿出屋頂**。
# 這也是床頭在左的理由：右邊是房間中間，天花板高的地方要留給書櫃和衣櫃。

# 踢腳板的底 = 地板深度 0。跟 ROOMS["pano"]["floor_rows"] 的起點是同一個數字，
# 檔案最下面有一行 assert 押著，改了一邊另一邊會當場炸掉
# 物件想畫到自己格子外面去的次數。
#
# **被切掉不會報錯，也不會在圖上留下痕跡**——書櫃的頂板和海報的托架都這樣
# 被靜靜削掉過一次，兩次都是把整張字元表倒出來比對才發現的。物件的 px()
# 本來就在做邊界檢查，順手數一下就有了，`pixel.py` 的 lint_clip() 會喊。
CLIPPED = {}


def _clip(name):
    CLIPPED[name] = CLIPPED.get(name, 0) + 1


WALL_FOOT = 7 * 16

# 左上角對齊哪一格。_bed() 和 place 吃的是同一個變數，兩邊不會漂掉
BED_AT = (1, 4)
BED_W, BED_H = 4, 5


def _bed():
    """4x5 的床。回傳 20 塊 16x16 的磚（從左到右、從上到下）。"""
    depth = 18       # 床往房間裡面佔多深
    mat = 21         # 床面（被子的頂面）離地多高
    drape = 7        # 被子從床面垂下來多長
    clear = 6        # 床架下緣離地多高
    hb = 38          # 床頭板多高
    pillow_x, pillow_w = 2, 17   # 枕頭離床頭那一端多遠、多寬
    sheet = 3        # 枕頭跟被子中間露多少床單
    duv = pillow_x + pillow_w + sheet    # 22，被子從這一欄開始
    hb_w = duv + 1   # 床頭板跟床單那一段一樣寬。**一定要比枕頭寬**（上面第 3 點）

    W, H = BED_W * 16, BED_H * 16
    off = BED_AT[1] * 16
    g = [["." for _ in range(W)] for _ in range(H)]

    def px(x, y, ch):
        y -= off
        if 0 <= x < W and 0 <= y < H:
            g[y][x] = ch
        else:
            _clip('bed')

    def rect(x0, x1, y0, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(min(x0, x1), max(x0, x1) + 1):
                px(x, y, ch)

    def Y(h, d=None):
        """離地 h、往裡面 d 的那一點畫在第幾列。上面那條式子就是這裡。"""
        return WALL_FOOT + (depth if d is None else d) - h

    back = Y(mat, 0)          # 被子靠牆那一緣    -> 91
    front = Y(mat)            # 被子的轉折線      -> 109
    hem = Y(mat - drape)      # 被子的下襬        -> 116
    rail = Y(clear)           # 木頭床架的下緣    -> 124
    floor = Y(0)              # 腳落地那條線      -> 130

    # 床底下的暗。**沒有這一塊床就是浮的**——腳畫得再對，
    # 底下透出地板還是會讀成一張貼在牆上的圖
    rect(1, W - 2, rail + 1, floor, "h")
    rect(2, W - 3, floor + 1, floor + 1, "k")

    for i in (1, W - 5):                        # 床頭、床尾各一隻腳
        rect(i, i + 3, rail + 1, floor, "w")
        rect(i + 3, i + 3, rail + 1, floor, "j")
        rect(i, i + 3, floor, floor, "o")

    # 床頭板。先畫，讓床架和枕頭壓在它前面（上面第 3 點）。
    # 一列一列畫、每一列自己算縮幾格，不是畫完再把角挖掉（上面第 6 點）。
    # 描邊自然就描滿兩側了，這條很重要：W(166,120,76) 跟磚的 B(150,98,78)
    # 差不到一個色階，少了側邊那條 o，床頭板會直接融進牆裡
    hy0 = Y(hb, 0)                              # 74
    for y in range(hy0, back + 1):
        cut = max(0, 2 - (y - hy0))             # 頂端兩列各收一格
        rect(cut, hb_w - 1 - cut, y, y, "o")
        if y > hy0:
            # 頂端第一條是受光的邊，再下去是頂面
            rect(cut + 1, hb_w - 2 - cut, y, y, "A" if y == hy0 + 1 else "W")

    # 木頭床架。被子只垂到 hem，這一條是露出來的那段（上面第 1 點）
    rect(1, W - 2, hem + 1, rail, "w")
    rect(1, W - 2, rail, rail, "o")
    rect(1, W - 2, rail - 1, rail - 1, "j")
    rect(1, W - 2, hem + 2, hem + 2, "W")
    rect(0, 0, hem + 2, rail, "o")
    rect(W - 1, W - 1, hem + 2, rail, "o")

    # 床面。**頂面**分兩段：床頭那一段是床單、翻折邊之後是被子。
    # **垂下來那一面整條都是被子**，不跟著分——理由在上面第 2 點
    rect(0, W - 1, back, back, "o")
    rect(0, duv, back + 1, front - 1, "p")      # 床單（頂面）
    rect(duv, W - 1, back + 1, front - 1, "L")  # 被子（頂面）
    rect(duv, duv, back, front, "o")            # 被子翻折過來那一道邊，只在頂面上

    rect(0, W - 1, front, front, "o")           # 頂面轉到垂面
    rect(0, W - 1, front + 1, hem, "C")         # 被子（垂面）
    rect(0, W - 1, hem, hem, "c")
    rect(0, W - 1, hem + 1, hem + 1, "o")

    # 床頭、床尾兩端的側緣。床頭那端是床單貼著磚牆，沒有這條會糊在一起
    rect(0, 0, back + 1, hem, "o")
    rect(W - 1, W - 1, back + 1, hem, "o")
    px(W - 2, back, "o")                        # 床尾的角收一格
    px(W - 1, back, ".")
    px(W - 1, back + 1, "o")
    px(W - 2, back + 1, "L")

    # 褶。垂下來那一面兩道直的，頂面兩道斜的——**斜的和不等距是重點**，
    # 三條等距的直線會讀成「正」字的筆畫（上面第 4 點）
    span0 = duv + 4
    step = W - 4 - span0
    for t in (0.34, 0.70):
        fx = int(round(span0 + step * t))
        rect(fx, fx, front + 2, hem - 1, "c")
    for t, d0, n in ((0.22, 3, 7), (0.63, 6, 6)):
        for k in range(n):
            px(int(round(span0 + step * t)) + k // 2, back + d0 + k, "C")

    # 枕頭。躺在床頭那一端，所以 d 從 1 開始算、離地比床面再高 ph。
    # 亮的（P）是整塊，暗的（p）只有靠外那三列（上面第 5 點）。
    # 四個角一樣是一列一列算縮幾格——枕頭底下有床單，挖下去就是一個洞（第 6 點）
    ph, pd = 5, 15
    pleft, pright = pillow_x, pillow_x + pillow_w - 1
    ptop, pbot = Y(mat + ph, 1), Y(mat + ph, 1 + pd)     # 87, 102
    for y in range(ptop, pbot + 1):
        cut = max(0, 2 - min(y - ptop, pbot - y))        # 枕頭是軟的，四個角都收
        rect(pleft + cut, pright - cut, y, y, "o")
        if ptop < y < pbot:
            rect(pleft + cut + 1, pright - cut - 1, y, y,
                 "p" if y >= pbot - 3 else "P")

    rows = ["".join(r) for r in g]
    return [[r[c * 16:(c + 1) * 16] for r in rows[t * 16:(t + 1) * 16]]
            for t in range(BED_H) for c in range(BED_W)]


BED_TILES = _bed()


