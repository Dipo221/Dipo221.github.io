#
#   一、只挪腳掌，身體不動          -> 像在滑行
#   二、整隻一起沉                  -> 有彈跳了，但腳被壓沒、頭跟著啄米
#   三、腳加長一排、頭完全鎖死      -> 腳回來了，但頭僵在那裡一樣怪
#   四、頭慢一拍跟上                -> 現在這個
#
# 第四版的關鍵是頭與身體不同步。身體第 1 幀沉下去、第 2 幀還在下面，
# 頭到第 2 幀才跟著沉——一個迴圈裡身體沉兩幀、頭只沉一幀，
# 頻率自然錯開。動畫上這叫 overlapping action：重的部位先動，
# 輕的部位拖一拍跟上，兩者同步反而是最假的。
#
# 「頭下沉、身體不下沉」這個組合畫不出來——頭往下推一格就會佔到身體
# 最上面那排。所以能用的只有三個狀態，剛好對上三格 sprite。
