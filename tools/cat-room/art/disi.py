def _v(base, changes):
    """複製底圖，只換掉指定的那幾排。

    寫成這樣不是為了省字，是為了讓「改一幀」在結構上不可能變成「重畫一幀」。
    每一幀重畫的話，幀跟幀之間會有幾格對不上，播起來整隻貓在抖——
    這種抖動盯著單幀看永遠找不出來。
    """
    out = list(base)
    for y, row in changes.items():
        out[y] = row
    return out


