def _eat(dy):
    """把頭疊到身體上，往下 dy 格。

    分成兩層不是為了省事：嚼東西是頭在動、身體不動，寫成兩層之後
    「某一幀不小心把身體也挪了一格」在結構上就不可能發生——
    跟 _v() 擋的是同一種錯，只是這裡動的是整塊而不是幾排。
    """
    out = [list(r) for r in EAT_BODY]
    for y, row in enumerate(EAT_HEAD):
        for x, ch in enumerate(row):
            if ch != "." and 0 <= y + dy < 16:
                out[y + dy][x] = ch
    return ["".join(r) for r in out]


