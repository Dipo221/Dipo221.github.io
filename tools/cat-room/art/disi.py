def _sag(base):
    """頭留在原位，身體沉一格：肩膀補一排，腳從四排壓成三排。

    補的那一排是複製肩膀（base[14]），不是複製 base[13]。
    base[13] 除了脖子的毛還帶著口鼻那格奶油的尾巴，複製它會讓奶油的
    尖端跟著身體多長一格——頭明明該不動，臉卻在變形。
    要補的是身體，就只能拿純身體的那一排來補。
    """
    return (list(base[0:14]) + [base[14]] + list(base[14:20])
            + [base[21], base[22], base[23]])


def _sink(base):
    """整隻沉一格，腳掌仍釘在 y23，腳一樣剩三排。"""
    return ["." * 24] + list(base[0:20]) + [base[21], base[22], base[23]]


