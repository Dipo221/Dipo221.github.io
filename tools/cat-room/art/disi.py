def _sag(base):
    """頭留在原位，身體沉一格：肩膀補一排，腳從三排壓成兩排。

    補的那一排是複製肩膀（base[9]），不是複製 y8。
    y8 那排除了脖子的毛還帶著下巴那格奶油色，複製它會讓下巴的白色
    尖端跟著身體多長一格——頭明明該不動，臉卻在變形。
    要補的是身體，就只能拿純身體的那一排來補。
    """
    return list(base[0:9]) + [base[9]] + list(base[9:13]) + [base[14], base[15]]


def _sink(base):
    """整隻沉一格，腳掌仍釘在 y15，腳一樣剩兩排。"""
    return ["." * 16] + list(base[0:13]) + [base[14], base[15]]


